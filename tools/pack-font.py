#!/usr/bin/env python3
"""Bake the web host's sans-serif fallback at native LCD pixel sizes."""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parent.parent
font_path = ROOT / 'assets/fonts/NotoSans-Regular.ttf'
out = ROOT / 'source/gen/font.c'
stamp = ROOT / 'build/font.sha256'
fingerprint = hashlib.sha256(font_path.read_bytes() + Path(__file__).read_bytes()).hexdigest()
if stamp.exists() and stamp.read_text() == fingerprint and out.exists() and (ROOT / 'build/gfx/font0.png').exists():
    raise SystemExit(0)
points = sorted(set(range(32, 256)) | set(range(0x2010, 0x2028)) | {0x2190, 0x2191, 0x2192, 0x2193, 0x2605, 0x2606})
page = Image.new('RGBA', (1024, 1024))
x = y = shelf = 0
rows = []
for size in range(10, 17):
    font = ImageFont.truetype(str(font_path), size)
    for code in points:
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch, anchor='ls')
        w, h = max(1, right-left), max(1, bottom-top)
        if x + w + 1 > 1024: x, y, shelf = 0, y + shelf, 0
        if y + h + 1 > 1024: raise SystemExit('Font atlas overflow')
        glyph = Image.new('RGBA', (w, h))
        ImageDraw.Draw(glyph).text((-left, -top), ch, font=font, fill='white', anchor='ls', stroke_width=0)
        page.paste(glyph, (x, y))
        rows.append((size, code, x, y, w, h, left, top, max(1, round(font.getlength(ch)))))
        x += w + 1; shelf = max(shelf, h + 1)
height = 1 << (y + shelf - 1).bit_length()
(ROOT / 'build/gfx').mkdir(parents=True, exist_ok=True)
page.crop((0, 0, 1024, height)).save(ROOT / 'build/gfx/font0.png')
out.write_text('// Generated by tools/pack-font.py.\n#include "assets.h"\nconst FontGlyph font_glyphs[] = {\n' + ''.join('  {' + ','.join(map(str, r)) + '},\n' for r in rows) + '};\nconst int font_glyph_count = ' + str(len(rows)) + ';\n')
stamp.write_text(fingerprint)
print(f'Native font: {len(rows)} glyphs, 1024x{height} LA8, sizes 10-16')
