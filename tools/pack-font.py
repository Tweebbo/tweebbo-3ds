#!/usr/bin/env python3
"""Bake the web host's sans-serif fallback at native LCD pixel sizes."""
from pathlib import Path
import hashlib
import json
import os
import subprocess
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parent.parent
font_path = ROOT / 'assets/fonts/NotoSans-Regular.ttf'
out = ROOT / 'source/gen/font.c'
stamp = ROOT / 'build/font.sha256'
cjk_path = Path(os.environ.get('TWEEBBO_CJK_FONT', '/usr/share/fonts/google-noto-sans-cjk-vf-fonts/NotoSansCJK-VF.ttc'))
symbol_path = Path(os.environ.get('TWEEBBO_SYMBOL_FONT','/usr/share/fonts/google-noto/NotoSansSymbols2-Regular.ttf'))
def charset(path, index=0):
    ranges = subprocess.check_output(['fc-query','--index',str(index),'--format','%{charset}',str(path)],text=True).split()
    return {code for span in ranges for ends in [span.split('-')] for code in range(int(ends[0],16),int(ends[-1],16)+1)}
latin_codes, symbol_codes = charset(font_path), charset(symbol_path)
cjk_codes = {'zh':charset(cjk_path,2), 'ja':charset(cjk_path,0)}
languages = ROOT / 'assets/fonts/language-glyphs.json'
language_chars = json.loads(languages.read_text())
fingerprint = hashlib.sha256(font_path.read_bytes() + cjk_path.read_bytes() + symbol_path.read_bytes() + languages.read_bytes() + Path(__file__).read_bytes()).hexdigest()
if stamp.exists() and stamp.read_text() == fingerprint and out.exists() and all((ROOT / f'build/gfx/{name}.png').exists() for name in ['font0','font-zh','font-ja']):
    raise SystemExit(0)
points = sorted(set(range(32, 256)) | set(range(0x2010, 0x2028)) | {0x2190, 0x2191, 0x2192, 0x2193, 0x2605, 0x2606} | {ord(c) for lang in ('es','fr','pt-BR') for c in language_chars[lang] if 255 < ord(c) < 0x3000} | {ord(c) for c in '中文日本語'})
for lang, chars in language_chars.items():
    common = {code for code in points if code in latin_codes or code in symbol_codes or code in cjk_codes['ja']}
    covered = common | cjk_codes.get(lang,set())
    missing = {ord(c) for c in chars if ord(c)>31 and ord(c) not in covered}
    if missing: raise SystemExit(f'{lang}: missing source-font glyphs {sorted(missing)}')
page = Image.new('RGBA', (1024, 1024))
x = y = shelf = 0
rows = []
for size in range(10, 17):
    font = ImageFont.truetype(str(font_path), size)
    symbols = ImageFont.truetype(str(symbol_path), size)
    cjk = ImageFont.truetype(str(cjk_path), size, index=0)
    cjk.set_variation_by_axes([400])
    for code in points:
        selected = font if code in latin_codes else symbols if code in symbol_codes else cjk
        ch = chr(code)
        left, top, right, bottom = selected.getbbox(ch, anchor='ls')
        w, h = max(1, right-left), max(1, bottom-top)
        if x + w + 1 > 1024: x, y, shelf = 0, y + shelf, 0
        if y + h + 1 > 1024: raise SystemExit('Font atlas overflow')
        glyph = Image.new('RGBA', (w, h))
        ImageDraw.Draw(glyph).text((-left, -top), ch, font=selected, fill='white', anchor='ls', stroke_width=0)
        page.paste(glyph, (x, y))
        rows.append((size, code, x, y, w, h, left, top, max(1, round(selected.getlength(ch)))))
        x += w + 1; shelf = max(shelf, h + 1)
height = 1 << (y + shelf - 1).bit_length()
(ROOT / 'build/gfx').mkdir(parents=True, exist_ok=True)
page.crop((0, 0, 1024, height)).save(ROOT / 'build/gfx/font0.png')
tables = '// Generated by tools/pack-font.py.\n#include "assets.h"\nconst FontGlyph font_glyphs[] = {\n' + ''.join('  {' + ','.join(map(str, r)) + '},\n' for r in rows) + '};\nconst int font_glyph_count = ' + str(len(rows)) + ';\n'
for lang, index in [('zh', 2), ('ja', 0)]:
    font = ImageFont.truetype(str(cjk_path), 13, index=index)
    font.set_variation_by_axes([400])
    codes = sorted({ord(c) for c in language_chars[lang] if 255 < ord(c) <= 65535 and ord(c) not in points})
    page = Image.new('RGBA', (1024, 1024))
    x = y = shelf = 0
    cjk_rows = []
    for code in codes:
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch, anchor='ls')
        w, h = max(1, right-left), max(1, bottom-top)
        if x + w + 1 > 1024: x, y, shelf = 0, y + shelf, 0
        if y + h + 1 > 1024: raise SystemExit(f'{lang}: CJK atlas exceeds one 1024-square page')
        ImageDraw.Draw(page).text((x-left, y-top), ch, font=font, fill='white', anchor='ls')
        cjk_rows.append((13, code, x, y, w, h, left, top, max(1, round(font.getlength(ch)))))
        x += w + 1; shelf = max(shelf, h + 1)
    height = 1 << (y + shelf - 1).bit_length()
    page.crop((0, 0, 1024, height)).save(ROOT / f'build/gfx/font-{lang}.png')
    tables += f'const FontGlyph font_{lang}_glyphs[] = {{\n' + ''.join('  {' + ','.join(map(str, r)) + '},\n' for r in cjk_rows) + f'}};\nconst int font_{lang}_count = {len(cjk_rows)};\n'
    print(f'{lang}: {len(cjk_rows)} CJK glyphs at 13 px, 1024x{height}, one resident page')
temporary = out.with_suffix('.c.tmp')
temporary.write_text(tables)
temporary.replace(out)
stamp.write_text(fingerprint)
print(f'Native font: {len(rows)} glyphs, 1024x{height} LA8, sizes 10-16')
