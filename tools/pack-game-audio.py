#!/usr/bin/env python3
"""Convert original game audio into bounded mono PCM banks for native playback."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
root = Path(__file__).resolve().parent.parent
web = Path(os.environ.get('TWEEBBO_WEB', root.parent/'Tweebbo-games-candidate-20261025'))
entries, reports = [], {}
for bank, source, folder, suffix in [(1,'fastfood','fastfood','mp3'),(2,'battleball','battle','flac')]:
    out=root/'romfs'/folder
    out.mkdir(parents=True,exist_ok=True)
    total=0
    report=[]
    for file in sorted((web/'client/public'/source).glob('*.'+suffix)):
        duration=float(subprocess.check_output(['ffprobe','-v','error','-show_entries','format=duration','-of','default=nw=1:nk=1',str(file)],text=True))
        rate=11025 if duration*22050>512*1024 else 22050
        if duration*rate>512*1024:
            raise SystemExit(f'{file.name} exceeds the native voice limit')
        target=out/(file.stem+'.pcm')
        subprocess.run(['ffmpeg','-v','error','-y','-i',str(file),'-ar',str(rate),'-ac','1','-f','s16le',str(target)],check=True)
        size=target.stat().st_size
        total+=size
        if size%2 or size>1024*1024:
            raise SystemExit(f'Invalid sample size: {file.name}')
        entries.append((bank,file.name,folder+'/'+target.name,rate,size//2))
        report.append({'source':file.name,'sha256':hashlib.sha256(file.read_bytes()).hexdigest(),'rate':rate,'samples':size//2})
    if total>4*1024*1024:
        raise SystemExit(f'{source} audio exceeds its 4 MiB resident bank budget')
    reports[source]={'pcmBytes':total,'sounds':report}
    print(f'{source}: {len(report)} sounds, {total} decoded PCM bytes')
(root/'source/gen/game_audio_assets.h').write_text('''// Generated by tools/pack-game-audio.py.
#pragma once
typedef struct {int bank;const char *name,*path;unsigned rate,samples;} GameSound;
extern const GameSound game_sounds[];
extern const unsigned game_sound_count;
''')
(root/'source/gen/game_audio_assets.c').write_text('#include "game_audio_assets.h"\nconst GameSound game_sounds[]={'+','.join('{'+f'{b},{json.dumps(n)},{json.dumps(p)},{r},{s}'+'}' for b,n,p,r,s in entries)+'};\nconst unsigned game_sound_count='+str(len(entries))+';\n')
(root/'build/game-audio-source.json').write_text(json.dumps(reports,indent=2)+'\n')
