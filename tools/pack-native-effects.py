#!/usr/bin/env python3
"""Pack frame plans resolved by the actual web effect controller."""
import hashlib
import json
import math
import struct
from pathlib import Path
from PIL import Image

PARTS = 'lh ls bd sh lg ch hd fc ey hr rh rs ri cp cc wa ca lc rc fa ea hrb ha he'.split()
ACTIONS = {'std': 1, 'sit': 2, 'crr': 3, 'drk': 4}


def collect(folder, packer):
    folder = Path(folder)
    data = json.loads((folder / 'effects.json').read_text())
    assert data['version'] == 1 and data['tickMilliseconds'] == 80
    images = {}
    for record in sorted(data['images'], key=lambda r: (-r['h'], r['id'])):
        image = Image.open(folder / 'images' / f"{record['id']}.png").convert('RGBA')
        assert image.size == (record['w'], record['h'])
        images[record['id']] = packer.add(image)
    assert sorted(images) == list(range(len(images)))
    assert len({a['id'] for a in data['animations']}) == len(data['animations'])
    for animation in data['animations']:
        assert len(animation['directions']) == 8
        for direction in animation['directions']:
            for name, period in [('still', animation['period']), ('moving', animation['movingPeriod'])]:
                assert len(direction[name]) == period and period > 0
                assert all(0 <= f < len(data['frames']) for f in direction[name])
    return data, images


def write_tables(collected, first_page, destination):
    data, images = collected
    destination = Path(destination)
    out = ['// Generated by tools/pack-native-effects.py from the web controller.', '#include "avatar_effects.h"']
    emit = out.append
    emit('const AvatarFxImage avatar_fx_images[] = {')
    for image in range(len(images)):
        page, x, y, w, h = images[image]
        assert first_page + page < 256
        emit(f'  {{{first_page+page},{x},{y},{w},{h}}},')
    emit('};')

    def layer(part):
        if part is None:
            return '{65535,0,0,0,0,0}'
        assert part['image'] in images
        assert all(math.isfinite(part[k]) and int(part[k]) == part[k] and abs(part[k]) < 32768 for k in ('x', 'y'))
        alpha = min(255, max(0, round(part['alpha'] * 255)))
        return '{%d,%d,%d,%d,%d,%d}' % (part['image'], part['x'], part['y'], -1 if part['depth'] < 0 else 1, part['ink'], alpha)

    bodies = [dict(hide=0, action=[0, 0, 0], frame=[0, 0, 0])]
    body_ids = {json.dumps(bodies[0], sort_keys=True): 0}
    layers, frames = [], []
    for frame in data['frames']:
        body = dict(hide=sum(1 << index for index, part in enumerate(PARTS) if part in frame['hide']), action=[0]*3, frame=[0]*3)
        for group, name in enumerate(('torso', 'leftarm', 'rightarm')):
            held = frame['parts'].get(name)
            if held:
                body['action'][group] = ACTIONS[held['action']]
                body['frame'][group] = held['frame']
                assert 0 <= held['frame'] < 256
        key = json.dumps(body, sort_keys=True)
        if key not in body_ids:
            body_ids[key] = len(bodies)
            bodies.append(body)
        frames.append((len(layers), len(frame['layers']), body_ids[key], frame['dx'], frame['dy']))
        layers.extend(layer(part) for part in frame['layers'])
    assert len(frames) < 65536 and len(bodies) < 65536
    emit('const AvatarFxLayer avatar_fx_layers[] = {')
    emit(',\n'.join('  '+part for part in layers) or '  {65535,0,0,0,0,0}')
    emit('};\nconst AvatarFxBody avatar_fx_bodies[] = {')
    for body in bodies:
        emit('  {%du,{%s},{%s}},' % (body['hide'], ','.join(map(str, body['action'])), ','.join(map(str, body['frame']))))
    emit('};')
    emit(f'const unsigned avatar_fx_body_count={len(bodies)};')
    emit('const AvatarFxFrame avatar_fx_frames[] = {')
    for row in frames:
        assert row[1] < 65536 and all(int(v) == v and abs(v) < 32768 for v in row[3:])
        emit('  {%d,%d,%d,%d,%d},' % row)
    emit('};')
    for animation in data['animations']:
        for name in ('still', 'moving'):
            indices = [index for direction in animation['directions'] for index in direction[name]]
            emit(f"static const u16 fx_{animation['id']}_{name}[]={{"+','.join(map(str, indices))+'};')
    emit('const AvatarFxAnimation avatar_fx_animations[] = {')
    for animation in sorted(data['animations'], key=lambda a: a['id']):
        appearance = animation['appearance']
        colors = [int(appearance[name].replace('#', '').rjust(8, 'F'), 16) if appearance else 0 for name in ('foreground', 'background')]
        shadows = ','.join(layer(direction['shadow']) for direction in animation['directions'])
        emit('  {%d,%d,%d,fx_%d_still,fx_%d_moving,{%s},0x%08xu,0x%08xu,%s},' % (
            animation['id'], animation['period'], animation['movingPeriod'], animation['id'], animation['id'], shadows, *colors, 'true' if appearance else 'false'))
    emit('};')
    emit(f"const unsigned avatar_fx_animation_count={len(data['animations'])};")
    (destination / 'avatar_effect_data.c').write_text('\n'.join(out)+'\n')
    (destination / 'avatar_effects.c').unlink(missing_ok=True)
    return dict(effects=len(data['animations']), frames=len(frames), bodies=len(bodies), layers=len(layers), images=len(images))


def encode_pixels(pixels):
    """RGBA runs and literals, each with a bounded 1..128-pixel length."""
    out = bytearray()
    count, index = len(pixels)//4, 0
    while index < count:
        run = 1
        while run < 128 and index+run < count and pixels[index*4:index*4+4] == pixels[(index+run)*4:(index+run)*4+4]:
            run += 1
        if run >= 3:
            out.append(0x80 | (run-1));out.extend(pixels[index*4:index*4+4]);index += run
            continue
        start = index;index += run
        while index < count and index-start < 128:
            if index+2 < count and pixels[index*4:index*4+4] == pixels[(index+1)*4:(index+1)*4+4] == pixels[(index+2)*4:(index+2)*4+4]:
                break
            index += 1
        index = min(index, start+128)
        out.append(index-start-1);out.extend(pixels[start*4:index*4])
    return out


def collect_penguin_pixels(source, destination):
    """Retain the same split penguin layers used by the existing room exporter."""
    source, destination = Path(source), Path(destination)
    spec = json.loads((source / 'data/igloo/penguin.json').read_text())
    atlas = Image.open(source / 'data/igloo/penguin.webp').convert('RGBA')
    frames = sorted({frame for clip in spec['clips'].values() for frame in clip})
    if frames != list(range(len(frames))):
        raise ValueError('Penguin pixel frame indices must be contiguous')
    images, records = [], []
    for frame in frames:
        width, height = spec['width'], spec['height']
        x, y = frame % spec['cols'] * width, frame // spec['cols'] * height
        image = atlas.crop((x, y, x + width, y + height))
        base, body = Image.new('RGBA', image.size), Image.new('RGBA', image.size)
        background, colored = [], []
        for red, green, blue, alpha in image.getdata():
            is_body = alpha and blue > 90 and blue > red * 1.25 and blue > green * 1.05
            shade = min(255, round(blue * 255 / 205))
            background.append((red, green, blue, 0 if is_body else alpha))
            colored.append((shade, shade, shade, alpha if is_body else 0))
        base.putdata(background); body.putdata(colored)
        for suffix, layer in [('base', base), ('body', body)]:
            box = layer.getbbox() or (0, 0, 1, 1)
            cropped = layer.crop(box)
            name = f'penguin-{frame}-{suffix}'
            records.append((name, cropped.width, cropped.height, spec['anchor'][0] - box[0], spec['anchor'][1] - box[1]))
            images.append(cropped)
    header = ['/* Generated by tools/pack-native-effects.py from the original penguin atlas. */', '#pragma once',
              f'#define PENGUIN_PIXEL_COUNT {len(records)}', 'static const PeopleSprite penguin_pixel_sprites[PENGUIN_PIXEL_COUNT] = {']
    header += [f'  {{"{name}",0,0,0,{width},{height},{rx},{ry}}},' for name, width, height, rx, ry in records]
    header.append('};')
    (destination / 'igloo_fx_pixels.h').write_text('\n'.join(header) + '\n')
    return images


def write_people_pixels(people, rects, page_files, graphics, path, extras=()):
    """Retain original atlas pixels for exact native appearance transformations."""
    graphics, path = Path(graphics), Path(path)
    pages, seen, payload, records = {}, {}, bytearray(), []
    base = 8 + (len(people)+len(extras))*12
    for index, _ in enumerate(people):
        page, x, y, w, h = rects[index]
        if page not in pages:
            pages[page] = Image.open(graphics / (page_files[page]+'.png')).convert('RGBA')
        raw = pages[page].crop((x, y, x+w, y+h)).tobytes()
        key = (w, h, hashlib.sha256(raw).digest())
        if key not in seen:
            encoded = encode_pixels(raw)
            seen[key] = (base+len(payload), len(encoded), w, h)
            payload.extend(encoded)
        records.append(seen[key])
    for image in extras:
        w, h = image.size
        raw = image.tobytes()
        key = (w, h, hashlib.sha256(raw).digest())
        if key not in seen:
            encoded = encode_pixels(raw)
            seen[key] = (base+len(payload), len(encoded), w, h)
            payload.extend(encoded)
        records.append(seen[key])
    with path.open('wb') as output:
        output.write(b'FXP1'+struct.pack('<I', len(records)))
        for record in records:
            output.write(struct.pack('<IIHH', *record))
        output.write(payload)
    return dict(sprites=len(records), penguinSprites=len(extras), uniqueImages=len(seen), bytes=path.stat().st_size,
                sha256=hashlib.sha256(path.read_bytes()).hexdigest())


