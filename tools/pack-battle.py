#!/usr/bin/env python3
"""Keep one Battle Ball arena and its shared effects resident, using original bitmaps."""
import hashlib
import importlib.util
import json
import os
import re
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent.parent
web = Path(os.environ.get('TWEEBBO_WEB', root.parent / 'Tweebbo-games-candidate-20261025'))
source, out = web / 'client/public/activities', root / 'build/battle'
out.mkdir(parents=True, exist_ok=True)
spec = importlib.util.spec_from_file_location('pack', root / 'tools/pack.py')
pack = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pack)
art = json.loads((source / 'art.json').read_text())
pages = [Image.open(source / file).convert('RGBA') for file in art['pages']]
presentation = json.loads((web / 'client/src/battle-presentation.json').read_text())
common = {name for name in art['sprites'] if re.match(r'^(tile\d|sh_wlk_bl_|s_bb2_|bb2_(efct_|stunned_|pickup_))', name)}
entries, banks, page_files, report = [], {}, [], {}
for arena in range(1, 6):
    model = art['maps'][str(arena)]
    names = set(common)
    for element in model['elements']:
        member = str(element.get('member', ''))
        if member in art['sprites']:
            names.add(member)
        if element.get('swapAnimType') == 'memberSwap':
            prefix = re.sub(r'\d+$', '', member)
            names.update(n for n in art['sprites'] if n.startswith(prefix) and n[len(prefix):].isdigit())
    images = {}
    for name in sorted(names):
        sprite = art['sprites'][name]
        x,y,w,h = (sprite[k] for k in ('x','y','w','h'))
        images[name] = (pages[sprite['page']].crop((x,y,x+w,y+h)), sprite['reg'])
    for name, overlay in presentation['overlay'].items():
        images[name] = (Image.open(web / 'client/public/battleball' / overlay['file']).convert('RGBA'), overlay['reg'])
    atlas, lookup = pack.Packer(), {}
    for name, (image, reg) in sorted(images.items(), key=lambda item: (-item[1][0].height, item[0])):
        lookup[name] = {'id':len(entries), 'reg':reg, 'w':image.width, 'h':image.height}
        entries.append(atlas.add(image))
    if len(atlas.pages)>4:
        raise SystemExit(f'Battle Ball arena {arena} exceeds four texture pages')
    files, size = [], 0
    for index, page in enumerate(atlas.pages):
        bbox = page.getbbox()
        height = max(8, 1 << ((bbox[3] if bbox else 1)-1).bit_length())
        name = f'arena{arena}_{index}'
        pack.save_png(page.crop((0,0,1024,height)), out/(name+'.png'))
        files.append(name)
        size += 1024*height*4
    banks[str(arena)] = lookup
    page_files.append(files)
    report[str(arena)] = {'rgbaBytes':size,'pages':files,'sprites':len(lookup)}
    print(f'Battle Ball arena {arena}: {len(lookup)} sprites, {len(files)} pages, {size} RGBA bytes')
(root/'source/gen/battle_assets.h').write_text('''// Generated by tools/pack-battle.py.
#pragma once
#include <stdint.h>
typedef struct { uint16_t page, x, y, w, h, ox, oy; } BattleSprite;
extern const BattleSprite battle_sprites[];
extern const unsigned battle_sprite_count, battle_page_count[5];
extern const char *const battle_page_files[5][4];
''')
rows = [f'{{{p},{x},{y},{w},{h},0,0}}' for p,x,y,w,h in entries]
(root/'source/gen/battle_assets.c').write_text('#include "battle_assets.h"\nconst BattleSprite battle_sprites[]={'+','.join(rows)+'};\nconst unsigned battle_sprite_count='+str(len(rows))+';\nconst unsigned battle_page_count[5]={'+','.join(str(len(f)) for f in page_files)+'};\nconst char *const battle_page_files[5][4]={'+','.join('{'+','.join(map(json.dumps,f))+'}' for f in page_files)+'};\n')
(out/'lookup.json').write_text(json.dumps({'maps':art['maps'],'banks':banks},separators=(',',':')))
(out/'source.json').write_text(json.dumps({'arenas':report,'artSha256':hashlib.sha256((source/'art.json').read_bytes()).hexdigest(),'presentationSha256':hashlib.sha256((web/'client/src/battle-presentation.json').read_bytes()).hexdigest()},indent=2)+'\n')
kept = {name for files in page_files for name in files}
for directory, suffix in [(out, '.png'), (root/'romfs/battle', '.t3x')]:
    for file in directory.glob('arena*'+suffix):
        if re.fullmatch(r'arena[1-5]_\d+',file.stem) and file.stem not in kept:
            file.unlink()
