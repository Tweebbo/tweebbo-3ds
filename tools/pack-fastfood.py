#!/usr/bin/env python3
"""Pack original Fast Food bitmaps for a 400-pixel native stage, loaded on demand."""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent.parent
web = Path(os.environ.get('TWEEBBO_WEB', root.parent / 'Tweebbo-games-candidate-20261025'))
source, out = web / 'client/public/fastfood', root / 'build/fastfood'
out.mkdir(parents=True, exist_ok=True)
spec = importlib.util.spec_from_file_location('pack', root / 'tools/pack.py')
pack = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pack)
manifest = json.loads((source / 'manifest.json').read_text())
resolution = 3
images, files = {}, {}
for entry in manifest.values():
    name = entry['file']
    if name not in images:
        image = Image.open(source / name).convert('RGBA')
        images[name] = image
        files[name] = hashlib.sha256((source / name).read_bytes()).hexdigest()
class Atlas:
    """One 1024-square page; split free rectangles without rotating sprite artwork."""
    def __init__(self):
        self.pages = [Image.new('RGBA', (1024, 1024))]
        self.free = [(0, 0, 1024, 1024)]

    def add(self, image):
        w, h = image.width + 2, image.height + 2
        fits = [(min(fw-w, fh-h), max(fw-w, fh-h), fy, fx)
                for fx, fy, fw, fh in self.free if w <= fw and h <= fh]
        if not fits:
            raise SystemExit('Fast Food exceeds its 4 MiB native texture budget')
        _, _, y, x = min(fits)
        fragments = []
        for fx, fy, fw, fh in self.free:
            if x >= fx+fw or x+w <= fx or y >= fy+fh or y+h <= fy:
                fragments.append((fx, fy, fw, fh))
                continue
            if x > fx: fragments.append((fx, fy, x-fx, fh))
            if x+w < fx+fw: fragments.append((x+w, fy, fx+fw-x-w, fh))
            if y > fy: fragments.append((fx, fy, fw, y-fy))
            if y+h < fy+fh: fragments.append((fx, y+h, fw, fy+fh-y-h))
        self.free = [r for i, r in enumerate(fragments) if not any(
            i != j and r[0] >= s[0] and r[1] >= s[1] and
            r[0]+r[2] <= s[0]+s[2] and r[1]+r[3] <= s[1]+s[3] and (r != s or j < i)
            for j, s in enumerate(fragments))]
        # Extrude a texel on every edge so bilinear sampling never reaches a neighbour.
        tile = Image.new('RGBA', (w, h))
        tile.paste(image, (1, 1))
        tile.paste(image.crop((0, 0, image.width, 1)), (1, 0))
        tile.paste(image.crop((0, image.height-1, image.width, image.height)), (1, h-1))
        tile.paste(image.crop((0, 0, 1, image.height)), (0, 1))
        tile.paste(image.crop((image.width-1, 0, image.width, image.height)), (w-1, 1))
        for dx, dy, sx, sy in [(0,0,0,0), (w-1,0,image.width-1,0),
                               (0,h-1,0,image.height-1), (w-1,h-1,image.width-1,image.height-1)]:
            tile.putpixel((dx, dy), image.getpixel((sx, sy)))
        self.pages[0].paste(tile, (x, y))
        return 0, x+1, y+1, image.width, image.height


atlas, entries, lookup, pending = Atlas(), [], {}, []
for name, image in sorted(images.items()):
    lookup[name] = {'ids': [], 'width': image.width, 'height': image.height}
    for angle in (0, 1, 2, 3) if name == manifest['missile_png']['file'] else (0,):
        scaled = image.convert('RGBa').resize((max(1, round(image.width/resolution)), max(1, round(image.height/resolution))), Image.Resampling.LANCZOS).convert('RGBA')
        if angle:
            scaled = scaled.transpose([None, Image.Transpose.ROTATE_270, Image.Transpose.ROTATE_180, Image.Transpose.ROTATE_90][angle])
        pending.append((name, angle, scaled))
for name, angle, scaled in sorted(pending, key=lambda p: (-p[2].width*p[2].height, p[0], p[1])):
    ids = lookup[name]['ids']
    while len(ids) <= angle: ids.append(0)
    ids[angle] = len(entries)
    entries.append(atlas.add(scaled))
page_names, texture_bytes = [], 0
for index, page in enumerate(atlas.pages):
    bbox = page.getbbox()
    height = max(8, 1 << ((bbox[3] if bbox else 1)-1).bit_length())
    name = f'color{index}'
    pack.save_png(page.crop((0,0,1024,height)), out / (name+'.png'))
    page_names.append(name)
    texture_bytes += 1024*height*4
(root / 'source/gen/fastfood_assets.h').write_text('''// Generated by tools/pack-fastfood.py.
#pragma once
#include <stdint.h>
typedef struct { uint16_t page, x, y, w, h, ox, oy; } FastfoodSprite;
extern const FastfoodSprite fastfood_sprites[];
extern const unsigned fastfood_sprite_count, fastfood_page_count;
extern const char *const fastfood_page_files[];
''')
rows = [f'{{{p},{x},{y},{w},{h},0,0}}' for p,x,y,w,h in entries]
(root / 'source/gen/fastfood_assets.c').write_text('#include "fastfood_assets.h"\nconst FastfoodSprite fastfood_sprites[]={'+','.join(rows)+'};\nconst unsigned fastfood_sprite_count='+str(len(rows))+';\nconst unsigned fastfood_page_count='+str(len(page_names))+';\nconst char *const fastfood_page_files[]={'+','.join(map(json.dumps,page_names))+'};\n')
(out/'lookup.json').write_text(json.dumps({'resolution':resolution,'sprites':{key:{**lookup[value['file']],'offset':value['offset']} for key,value in manifest.items()}},separators=(',',':')))
(out/'source.json').write_text(json.dumps({'profile':'native-400','resolution':resolution,'filter':'premultiplied-lanczos-bilinear','edgePadding':1,'rgbaBytes':texture_bytes,'pages':page_names,'files':files},indent=2)+'\n')
print(f'Fast Food: {len(entries)} sprites, {len(page_names)} pages, {texture_bytes} decoded RGBA bytes')
