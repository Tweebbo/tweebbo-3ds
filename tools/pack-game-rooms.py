#!/usr/bin/env python3
"""Export stable room slugs and digit height units from the selective room manifest."""
import json
import sys
from pathlib import Path

source, target = map(Path, sys.argv[1:3])
ports_path = source / 'data/public-rooms/ports.json'
ports = json.loads(ports_path.read_text()) if ports_path.exists() else {'version': 1, 'rooms': []}
if ports['version'] != 1:
    raise SystemExit('Unsupported game room manifest')
rooms = json.loads((source / 'data/public-rooms/index.json').read_text())
lines = ['// Generated by tools/pack-game-rooms.py.', '#pragma once',
         'typedef struct { const char *model, *slug; unsigned height_unit; } GameRoomPort;',
         'static const GameRoomPort game_room_ports[] = {']
for port in ports['rooms']:
    room = rooms[port['model']]
    unit = room['heightUnit']
    if unit not in (16, 32):
        raise SystemExit('Unsupported native room height unit')
    lines.append('  {%s, %s, %d},' % (json.dumps(port['model']), json.dumps(port['slug']), unit))
lines += ['  {0, 0, 0}', '};', '']
target.mkdir(parents=True, exist_ok=True)
(target / 'game_rooms.h').write_text('\n'.join(lines))
