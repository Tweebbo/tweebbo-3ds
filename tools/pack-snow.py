#!/usr/bin/env python3
"""Preserve SnowWar pixels and Director inks in separately loaded 3DS textures."""
import importlib.util
import json
import os
import subprocess
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
WEB = Path(os.environ.get('TWEEBBO_WEB', ROOT.parent / 'Tweebbo-Vercel'))
SRC = WEB / 'client/public/snowstorm'
OUT = ROOT / 'build/snow'
ROM = ROOT / 'romfs/snow'
OUT.mkdir(parents=True, exist_ok=True)
ROM.mkdir(parents=True, exist_ok=True)
spec = importlib.util.spec_from_file_location('pack', ROOT / 'tools/pack.py')
pack = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pack)
atlas = json.loads((SRC / 'sprites.json').read_text())
pages = [Image.open(SRC / p).convert('RGBA') for p in atlas['pages']]
groups = [pack.Packer(), pack.Packer()]
entries = []
lookup = {}
for name, s in sorted(atlas['sprites'].items()):
    if not name.startswith(('sh_', 'sw_', 's_snowball', 'snowball', 'snowwar_arena', 'hit', 'hiliter_pub')):
        continue
    original = pages[s['page']].crop((s['x'], s['y'], s['x'] + s['w'], s['y'] + s['h']))
    inks = (0,) if name in ('snowwar_arena', 'snowball', 'snowball_sd') else (36,) if name.startswith(('sw_avatar_hilite', 'hiliter_pub')) or '_ey_' in name else (8,)
    for ink in inks:
        im = original.copy()
        if s['bpp'] <= 8 and ink:
            if ink == 36:
                im.putdata([(r, g, b, 0 if (r, g, b) == (255, 255, 255) else a) for r, g, b, a in im.getdata()])
            else:
                # Flood only border-connected white; interior white stays opaque.
                mask = Image.new('RGB', im.size)
                mask.putdata([(255, 255, 255) if p[:3] == (255, 255, 255) else (0, 0, 0) for p in im.getdata()])
                for x in range(im.width):
                    for y in (0, im.height - 1):
                        if mask.getpixel((x, y)) == (255, 255, 255): ImageDraw.floodfill(mask, (x, y), (255, 0, 0))
                for y in range(im.height):
                    for x in (0, im.width - 1):
                        if mask.getpixel((x, y)) == (255, 255, 255): ImageDraw.floodfill(mask, (x, y), (255, 0, 0))
                im.putdata([(r, g, b, 0 if m == (255, 0, 0) else a) for (r, g, b, a), m in zip(im.getdata(), mask.getdata())])
        box = im.getbbox() or (0, 0, 1, 1)
        crop = im.crop(box)
        gray = all(r == g == b for r, g, b, a in crop.getdata() if a)
        group = int(gray)
        page, x, y, w, h = groups[group].add(crop)
        lookup[f'{name}/{ink}'] = len(entries)
        entries.append((group, page, x, y, w, h, box[0], box[1]))
files = []
offsets = []
for group, p in enumerate(groups):
    offsets.append(len(files))
    for i, im in enumerate(p.pages):
        name = f'{"gray" if group else "color"}{i}'
        files.append(name)
        bbox = im.getbbox()
        height = max(8, 1 << ((bbox[3] if bbox else 1) - 1).bit_length())
        pack.save_png(im.crop((0, 0, 1024, height)), OUT / f'{name}.png')
header = '''/* Generated by tools/pack-snow.py. */
#pragma once
#include <stdint.h>
typedef struct { uint16_t page, x, y, w, h, ox, oy; } SnowSprite;
extern const SnowSprite snow_sprites[];
extern const unsigned snow_sprite_count, snow_page_count;
extern const char *const snow_page_files[];
'''
(ROOT / 'source/gen/snow_assets.h').write_text(header)
rows = [f'{{{offsets[g]+p},{x},{y},{w},{h},{ox},{oy}}}' for g,p,x,y,w,h,ox,oy in entries]
(ROOT / 'source/gen/snow_assets.c').write_text('#include "snow_assets.h"\nconst SnowSprite snow_sprites[]={\n'+',\n'.join(rows)+'};\nconst unsigned snow_sprite_count='+str(len(rows))+';\nconst unsigned snow_page_count='+str(len(files))+';\nconst char *const snow_page_files[]={'+','.join(json.dumps(n) for n in files)+'};\n')
(OUT / 'lookup.json').write_text(json.dumps(lookup, separators=(',', ':')))
print(f'Snow Storm: {len(entries)} ink variants, {len(files)} texture pages')
for folder, suffix in ((OUT, '.png'), (ROM, '.t3x')):
    for file in folder.glob('*' + suffix):
        if file.stem not in files: file.unlink()
for source in (SRC / 'sounds').glob('*.mp3'):
    target = ROM / (source.stem + '.pcm')
    if not target.exists() or target.stat().st_mtime < source.stat().st_mtime:
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(source), '-ac', '1', '-ar', '22050', '-f', 's16le', str(target)], check=True)
